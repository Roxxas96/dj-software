    use super::*;

    /// A two-element graph `y = x + Cast(w)`, with `w` a float16 weight input, and the
    /// safetensors file holding `w`.
    fn tiny() -> (Vec<u8>, Vec<u8>) {
        use onnx::tensor_proto::DataType;
        use onnx::tensor_shape_proto::{Dimension, dimension};
        let value = |name: &str, elem_type: DataType| onnx::ValueInfoProto {
            name: name.into(),
            r#type: Some(onnx::TypeProto {
                value: Some(onnx::type_proto::Value::TensorType(
                    onnx::type_proto::Tensor {
                        elem_type: elem_type as i32,
                        shape: Some(onnx::TensorShapeProto {
                            dim: vec![Dimension {
                                value: Some(dimension::Value::DimValue(2)),
                                ..Default::default()
                            }],
                        }),
                    },
                )),
                ..Default::default()
            }),
            ..Default::default()
        };
        let node = |op: &str, inputs: &[&str], output: &str| onnx::NodeProto {
            op_type: op.into(),
            input: inputs.iter().map(|&s| s.into()).collect(),
            output: vec![output.into()],
            name: format!("{op}/{output}"),
            ..Default::default()
        };
        let mut cast = node("Cast", &["w"], "w32");
        cast.attribute.push(onnx::AttributeProto {
            name: "to".into(),
            i: DataType::Float as i64,
            r#type: onnx::attribute_proto::AttributeType::Int as i32,
            ..Default::default()
        });
        let model = onnx::ModelProto {
            ir_version: 8,
            opset_import: vec![onnx::OperatorSetIdProto {
                domain: String::new(),
                version: 17,
            }],
            graph: Some(onnx::GraphProto {
                name: "tiny".into(),
                node: vec![cast, node("Add", &["x", "w32"], "y")],
                input: vec![value("x", DataType::Float), value("w", DataType::Float16)],
                output: vec![value("y", DataType::Float)],
                ..Default::default()
            }),
            ..Default::default()
        };
        // 1.0 and -2.0 as little-endian half floats.
        let half = [0x00, 0x3c, 0x00, 0xc0];
        let view =
            safetensors::tensor::TensorView::new(safetensors::Dtype::F16, vec![2], &half).unwrap();
        let weights = safetensors::serialize([("w", view)], None).unwrap();
        (model.encode_to_vec(), weights)
    }

    /// How the test server answers one request.
    enum Answer {
        Body(Vec<u8>),
        /// Announces the whole body, sends `n` bytes of it and closes.
        Truncated(Vec<u8>, usize),
    }

    /// Serves `answers` on localhost, one per connection; returns the URL and the requests.
    fn serve(answers: Vec<Answer>) -> (String, JoinHandle<Vec<String>>) {
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        let url = format!(
            "http://{}/955717e8.safetensors",
            listener.local_addr().unwrap()
        );
        let handle = std::thread::spawn(move || {
            let mut requests = Vec::new();
            for answer in answers {
                let (mut stream, _) = listener.accept().unwrap();
                let mut reader = std::io::BufReader::new(stream.try_clone().unwrap());
                let mut request = String::new();
                loop {
                    let mut line = String::new();
                    if reader.read_line(&mut line).unwrap() == 0 || line == "\r\n" {
                        break;
                    }
                    request.push_str(&line);
                }
                requests.push(request);
                let (body, sent) = match &answer {
                    Answer::Body(body) => (body, body.len()),
                    Answer::Truncated(body, n) => (body, *n),
                };
                let head = format!(
                    "HTTP/1.1 200 OK\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
                    body.len()
                );
                stream.write_all(head.as_bytes()).unwrap();
                let _ = stream.write_all(&body[..sent]);
            }
            requests
        });
        (url, handle)
    }

    fn plan<'a>(
        dir: &Path,
        url: String,
        graph: &'a [u8],
        weights_sha256: &'a str,
        filled_sha256: &'a str,
    ) -> Plan<'a> {
        Plan {
            weights_url: url,
            weights_sha256,
            weights_max_bytes: 1 << 20,
            graph,
            inputs_left: &["x"],
            filled_sha256,
            model_path: dir.join("models").join("tiny.onnx"),
            allow_http: true,
            test_vector: false,
            warm: false,
            coreml_cache: None,
        }
    }

    /// Every file under `dir`, relative.
    fn files(dir: &Path) -> Vec<String> {
        let mut found = Vec::new();
        let mut stack = vec![dir.to_path_buf()];
        while let Some(at) = stack.pop() {
            for entry in std::fs::read_dir(&at).into_iter().flatten().flatten() {
                if entry.file_type().unwrap().is_dir() {
                    stack.push(entry.path());
                } else {
                    let path = entry.path();
                    found.push(path.strip_prefix(dir).unwrap().display().to_string());
                }
            }
        }
        found.sort();
        found
    }

    #[test]
    fn setup_rejects_a_bad_checksum() {
        let (graph, weights) = tiny();
        let filled = sha256_hex(&fill(&graph, &weights, &["x"]).unwrap());
        let good = sha256_hex(&weights);

        // Tampered weights.
        let mut tampered = weights.clone();
        *tampered.last_mut().unwrap() ^= 1;
        let dir = tempfile::tempdir().unwrap();
        let (url, server) = serve(vec![Answer::Body(tampered)]);
        let error = run(&plan(dir.path(), url, &graph, &good, &filled), &|_| {}).unwrap_err();
        assert!(
            matches!(
                error,
                SetupError::Checksum {
                    what: "the downloaded weights",
                    ..
                }
            ),
            "{error}"
        );
        server.join().unwrap();
        assert_eq!(files(dir.path()), Vec::<String>::new());

        // Good weights, but the filled model is not the recorded one.
        let wrong = "0".repeat(64);
        let (url, server) = serve(vec![Answer::Body(weights)]);
        let error = run(&plan(dir.path(), url, &graph, &good, &wrong), &|_| {}).unwrap_err();
        assert!(
            matches!(
                error,
                SetupError::Checksum {
                    what: "the filled model",
                    ..
                }
            ),
            "{error}"
        );
        server.join().unwrap();
        assert!(!dir.path().join("models/tiny.onnx").exists());
        assert_eq!(
            files(dir.path()),
            Vec::<String>::new(),
            "no partial file left"
        );
    }

    #[test]
    fn setup_is_atomic() {
        let (graph, weights) = tiny();
        let expected = fill(&graph, &weights, &["x"]).unwrap();
        let filled = sha256_hex(&expected);
        let good = sha256_hex(&weights);
        let dir = tempfile::tempdir().unwrap();
        let model = dir.path().join("models/tiny.onnx");

        // A download cut short writes nothing.
        let half = weights.len() / 2;
        let (url, server) = serve(vec![Answer::Truncated(weights.clone(), half)]);
        let error = run(&plan(dir.path(), url, &graph, &good, &filled), &|_| {}).unwrap_err();
        assert!(matches!(error, SetupError::Download { .. }), "{error}");
        server.join().unwrap();
        assert_eq!(files(dir.path()), Vec::<String>::new());

        // A failed attempt leaves an existing (stale) file as it was.
        std::fs::create_dir_all(model.parent().unwrap()).unwrap();
        std::fs::write(&model, b"stale").unwrap();
        let (url, server) = serve(vec![Answer::Truncated(weights.clone(), half)]);
        run(&plan(dir.path(), url, &graph, &good, &filled), &|_| {}).unwrap_err();
        server.join().unwrap();
        assert_eq!(std::fs::read(&model).unwrap(), b"stale");
        assert_eq!(files(dir.path()), ["models/tiny.onnx"]);
        // So does a model that is filled but fails verification.
        let wrong = "0".repeat(64);
        let (url, server) = serve(vec![Answer::Body(weights.clone())]);
        run(&plan(dir.path(), url, &graph, &good, &wrong), &|_| {}).unwrap_err();
        server.join().unwrap();
        assert_eq!(std::fs::read(&model).unwrap(), b"stale");
        assert_eq!(files(dir.path()), ["models/tiny.onnx"]);

        // A good run replaces it with the verified model and leaves nothing else.
        let (url, server) = serve(vec![Answer::Body(weights)]);
        run(&plan(dir.path(), url, &graph, &good, &filled), &|_| {}).unwrap();
        server.join().unwrap();
        assert_eq!(std::fs::read(&model).unwrap(), expected);
        assert_eq!(files(dir.path()), ["models/tiny.onnx"]);
    }

    #[test]
    fn setup_is_idempotent() {
        let (graph, weights) = tiny();
        let filled = sha256_hex(&fill(&graph, &weights, &["x"]).unwrap());
        let good = sha256_hex(&weights);
        let dir = tempfile::tempdir().unwrap();
        let (url, server) = serve(vec![Answer::Body(weights)]);
        run(
            &plan(dir.path(), url.clone(), &graph, &good, &filled),
            &|_| {},
        )
        .unwrap();
        server.join().unwrap();
        let model = dir.path().join("models/tiny.onnx");
        let written = std::fs::metadata(&model).unwrap().modified().unwrap();

        // The server is gone: a second run must not need it.
        let events = RefCell::new(Vec::new());
        run(&plan(dir.path(), url, &graph, &good, &filled), &|e| {
            events.borrow_mut().push(e)
        })
        .unwrap();
        assert_eq!(*events.borrow(), [SetupEvent::AlreadyInstalled]);
        assert_eq!(
            std::fs::metadata(&model).unwrap().modified().unwrap(),
            written
        );
    }

    #[test]
    fn setup_reports_progress_and_sends_no_personal_data() {
        let (graph, weights) = tiny();
        let filled = sha256_hex(&fill(&graph, &weights, &["x"]).unwrap());
        let good = sha256_hex(&weights);
        let dir = tempfile::tempdir().unwrap();
        let length = weights.len() as u64;
        let (url, server) = serve(vec![Answer::Body(weights)]);
        let events = RefCell::new(Vec::new());
        run(&plan(dir.path(), url, &graph, &good, &filled), &|e| {
            events.borrow_mut().push(e)
        })
        .unwrap();
        let events = events.into_inner();
        assert_eq!(
            events.first(),
            Some(&SetupEvent::Downloading {
                done: 0,
                total: Some(length)
            })
        );
        assert!(events.contains(&SetupEvent::Downloading {
            done: length,
            total: Some(length)
        }));
        assert_eq!(events.last(), Some(&SetupEvent::Filling));

        let requests = server.join().unwrap();
        let request = &requests[0];
        assert!(
            request.starts_with("GET /955717e8.safetensors HTTP/1.1"),
            "{request}"
        );
        let agent = request.lines().find_map(|l| {
            l.to_ascii_lowercase()
                .strip_prefix("user-agent: ")
                .map(str::to_owned)
        });
        assert_eq!(agent.as_deref(), Some(USER_AGENT));
        assert!(!request.contains('@'), "{request}");
        let headers: Vec<&str> = request
            .lines()
            .skip(1)
            .filter_map(|l| l.split(':').next())
            .collect();
        for header in headers {
            let header = header.to_ascii_lowercase();
            assert!(
                ["host", "user-agent", "accept", "accept-encoding"].contains(&header.as_str()),
                "unexpected header {header}"
            );
        }
    }

