/// A generic User-Agent: no personal data is ever sent (ruling R3).
const USER_AGENT: &str = "open-jockey-dev";

/// What `setup` is doing, for its progress display.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum SetupEvent {
    /// The model is already there and verified; nothing is downloaded.
    AlreadyInstalled,
    /// Downloading the weights: `done` bytes of `total`.
    Downloading { done: u64, total: Option<u64> },
    /// Filling the graph with the weights.
    Filling,
    /// The filled model's bytes differ from the record: checking it with the test vector.
    TestVector,
    /// Compiling the model for CoreML once, so the first track load is quick; `seconds`
    /// so far (about a minute in all).
    Warming { seconds: u64 },
}

/// Why `setup` failed. Nothing is written unless every check passed.
#[derive(Debug, Error)]
pub enum SetupError {
    #[error("downloading {url}: {message}")]
    Download { url: String, message: String },
    #[error("{what} has SHA-256 {actual}, expected {expected}")]
    Checksum {
        what: &'static str,
        expected: String,
        actual: String,
    },
    #[error("filling the model: {0}")]
    Fill(String),
    #[error("{}: {source}", path.display())]
    Io {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("the filled model fails its test vector: {0}")]
    TestVector(String),
    #[error("opening the model: {0}")]
    Warm(String),
}

/// Everything `setup` needs; [`Plan::htdemucs`] is the real one, tests use small ones.
#[derive(Debug, Clone)]
pub(crate) struct Plan<'a> {
    pub(crate) weights_url: String,
    pub(crate) weights_sha256: &'a str,
    /// The download is refused past this size.
    pub(crate) weights_max_bytes: u64,
    pub(crate) graph: &'a [u8],
    /// The graph inputs left once every weight is filled in.
    pub(crate) inputs_left: &'a [&'a str],
    pub(crate) filled_sha256: &'a str,
    pub(crate) model_path: PathBuf,
    /// Plain `http://` is allowed (tests on localhost).
    pub(crate) allow_http: bool,
    /// Check a model whose bytes differ from `filled_sha256` with the test vector
    /// (feature `model`); otherwise such a model is refused.
    pub(crate) test_vector: bool,
    /// Open a CoreML session once after writing (macOS, feature `model`), with this
    /// compile cache (`None`: [`crate::coreml_cache_dir`]).
    pub(crate) warm: bool,
    pub(crate) coreml_cache: Option<PathBuf>,
}

impl Plan<'static> {
    pub(crate) fn htdemucs(model_path: PathBuf) -> Self {
        Self {
            weights_url: WEIGHTS_URL.into(),
            weights_sha256: WEIGHTS_SHA256,
            weights_max_bytes: WEIGHTS_BYTES,
            graph: GRAPH,
            inputs_left: &["mix", "mag"],
            filled_sha256: FILLED_SHA256,
            model_path,
            allow_http: false,
            test_vector: true,
            warm: cfg!(target_os = "macos"),
            coreml_cache: None,
        }
    }
}

/// Fetches the htdemucs weights from their author, fills the model and writes it to
/// [`crate::model_path`], atomically; then, on macOS, compiles it for CoreML once. An
/// already installed, verified model is kept (nothing is downloaded).
pub fn setup(progress: &dyn Fn(SetupEvent)) -> Result<(), SetupError> {
    run(&Plan::htdemucs(crate::model_path()), progress)
}

pub(crate) fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn sha256_hex(bytes: &[u8]) -> String {
    hex(&Sha256::digest(bytes))
}

fn io_error(path: &Path) -> impl FnOnce(std::io::Error) -> SetupError + '_ {
    move |source| SetupError::Io {
        path: path.to_path_buf(),
        source,
    }
}

/// `true` when `path` holds the verified model.
fn installed(path: &Path, filled_sha256: &str) -> bool {
    std::fs::read(path).is_ok_and(|bytes| sha256_hex(&bytes) == filled_sha256)
}

pub(crate) fn run(plan: &Plan<'_>, progress: &dyn Fn(SetupEvent)) -> Result<(), SetupError> {
    if installed(&plan.model_path, plan.filled_sha256) {
        progress(SetupEvent::AlreadyInstalled);
    } else {
        let weights = download(plan, progress)?;
        progress(SetupEvent::Filling);
        let filled = fill(plan.graph, &weights, plan.inputs_left)?;
        drop(weights);
        write_verified(plan, &filled, progress)?;
    }
    if plan.warm {
        warm(&plan.model_path, plan.coreml_cache.clone(), progress)?;
    }
    Ok(())
}

/// Downloads the weights into memory, checking their size limit and SHA-256.
fn download(plan: &Plan<'_>, progress: &dyn Fn(SetupEvent)) -> Result<Vec<u8>, SetupError> {
    use ureq::tls::{RootCerts, TlsConfig, TlsProvider};
    let failed = |message: String| SetupError::Download {
        url: plan.weights_url.clone(),
        message,
    };
    let agent = ureq::Agent::config_builder()
        .user_agent(USER_AGENT)
        .https_only(!plan.allow_http)
        .timeout_connect(Some(Duration::from_secs(30)))
        .timeout_recv_body(Some(Duration::from_secs(60)))
        .tls_config(
            TlsConfig::builder()
                .provider(TlsProvider::NativeTls)
                .root_certs(RootCerts::PlatformVerifier)
                .build(),
        )
        .build()
        .new_agent();
    let mut response = agent
        .get(&plan.weights_url)
        .call()
        .map_err(|e| failed(e.to_string()))?;
    let total = response.body().content_length();
    if total.is_some_and(|total| total > plan.weights_max_bytes) {
        return Err(failed(format!("{} bytes is too large", total.unwrap_or(0))));
    }
    let mut reader = response
        .body_mut()
        .with_config()
        .limit(plan.weights_max_bytes + 1)
        .reader();
    let mut bytes = Vec::with_capacity(total.unwrap_or(0) as usize);
    let mut hasher = Sha256::new();
    let mut buffer = vec![0u8; 1 << 16];
    progress(SetupEvent::Downloading { done: 0, total });
    loop {
        let read = match reader.read(&mut buffer) {
            Ok(0) => break,
            Ok(read) => read,
            Err(e) if e.kind() == std::io::ErrorKind::Interrupted => continue,
            Err(e) => return Err(failed(e.to_string())),
        };
        hasher.update(&buffer[..read]);
        bytes.extend_from_slice(&buffer[..read]);
        if bytes.len() as u64 > plan.weights_max_bytes {
            return Err(failed("the download is larger than the weights".into()));
        }
        progress(SetupEvent::Downloading {
            done: bytes.len() as u64,
            total,
        });
    }
    let actual = hex(&hasher.finalize());
    if actual != plan.weights_sha256 {
        return Err(SetupError::Checksum {
            what: "the downloaded weights",
            expected: plan.weights_sha256.into(),
            actual,
        });
    }
    Ok(bytes)
}

/// Fills `graph` with the safetensors `weights`: each graph input named as a tensor
/// becomes an initializer with the tensor's float16 bytes, unchanged (the graph casts them
/// itself). Fails unless every tensor is used and exactly `inputs_left` remain.
pub(crate) fn fill(
    graph: &[u8],
    weights: &[u8],
    inputs_left: &[&str],
) -> Result<Vec<u8>, SetupError> {
    use onnx::tensor_proto::DataType;
    use onnx::tensor_shape_proto::dimension::Value as Dim;
    use onnx::type_proto::Value as Type;
    let fail = |message: String| SetupError::Fill(message);
    let mut model =
        onnx::ModelProto::decode(graph).map_err(|e| fail(format!("reading the graph: {e}")))?;
    let tensors = safetensors::SafeTensors::deserialize(weights)
        .map_err(|e| fail(format!("reading the weights: {e}")))?;
    let body = model
        .graph
        .as_mut()
        .ok_or_else(|| fail("the model has no graph".into()))?;
    let mut kept = Vec::new();
    let mut filled = 0;
    for input in std::mem::take(&mut body.input) {
        let Ok(view) = tensors.tensor(&input.name) else {
            kept.push(input);
            continue;
        };
        let name = &input.name;
        let Some(Type::TensorType(tensor)) = input.r#type.as_ref().and_then(|t| t.value.as_ref())
        else {
            return Err(fail(format!("{name}: the graph input is not a tensor")));
        };
        if tensor.elem_type != DataType::Float16 as i32 {
            return Err(fail(format!(
                "{name}: graph type {} is not float16",
                tensor.elem_type
            )));
        }
        if view.dtype() != safetensors::Dtype::F16 {
            return Err(fail(format!(
                "{name}: weights type {:?} is not F16",
                view.dtype()
            )));
        }
        let dims: Vec<i64> = tensor
            .shape
            .as_ref()
            .map(|shape| {
                shape
                    .dim
                    .iter()
                    .map(|d| match d.value {
                        Some(Dim::DimValue(v)) => v,
                        _ => -1,
                    })
                    .collect()
            })
            .unwrap_or_default();
        let want: Vec<i64> = view.shape().iter().map(|&d| d as i64).collect();
        if dims != want {
            return Err(fail(format!(
                "{name}: graph shape {dims:?}, weights shape {want:?}"
            )));
        }
        body.initializer.push(onnx::TensorProto {
            name: input.name.clone(),
            data_type: DataType::Float16 as i32,
            dims,
            raw_data: view.data().to_vec(),
            ..Default::default()
        });
        filled += 1;
    }
    body.input = kept;
    if filled != tensors.len() {
        return Err(fail(format!(
            "the graph takes {filled} of the {} weight tensors",
            tensors.len()
        )));
    }
    let left: Vec<&str> = body.input.iter().map(|i| i.name.as_str()).collect();
    if left != inputs_left {
        return Err(fail(format!(
            "inputs left {left:?}, expected {inputs_left:?}"
        )));
    }
    Ok(model.encode_to_vec())
}

/// Writes `filled` to a temporary file beside the model, verifies it, then renames it into
/// place: the model path holds either nothing (or what it held) or a verified model.
fn write_verified(
    plan: &Plan<'_>,
    filled: &[u8],
    progress: &dyn Fn(SetupEvent),
) -> Result<(), SetupError> {
    let path = &plan.model_path;
    let dir = path.parent().unwrap_or(Path::new("."));
    std::fs::create_dir_all(dir).map_err(io_error(dir))?;
    let mut temp = tempfile::Builder::new()
        .prefix(".htdemucs-")
        .suffix(".partial")
        .tempfile_in(dir)
        .map_err(io_error(dir))?;
    temp.write_all(filled).map_err(io_error(temp.path()))?;
    temp.as_file().sync_all().map_err(io_error(temp.path()))?;

    let actual = sha256_hex(filled);
    if actual != plan.filled_sha256 {
        // Another protobuf encoder writes other bytes for the same model: the test vector
        // then decides.
        if !plan.test_vector {
            return Err(SetupError::Checksum {
                what: "the filled model",
                expected: plan.filled_sha256.into(),
                actual,
            });
        }
        progress(SetupEvent::TestVector);
        check_test_vector(temp.path())?;
    }
    temp.persist(path).map_err(|e| SetupError::Io {
        path: path.clone(),
        source: e.error,
    })?;
    Ok(())
}

#[cfg(feature = "model")]
fn check_test_vector(path: &Path) -> Result<(), SetupError> {
    crate::model::check_test_vector(path).map_err(SetupError::TestVector)
}

#[cfg(not(feature = "model"))]
fn check_test_vector(_: &Path) -> Result<(), SetupError> {
    Err(SetupError::TestVector(
        "this build has no model runtime (feature `model`)".into(),
    ))
}

/// Opens the model once with CoreML (and runs it once), so its slow first compile lands in
/// the caches now. Measured: the compile is cached per executable as well as in
/// `coreml_cache`, so this spares the first track load of the same `open-jockey` binary;
/// a binary at another path compiles once more.
#[cfg(feature = "model")]
fn warm(
    path: &Path,
    coreml_cache: Option<PathBuf>,
    progress: &dyn Fn(SetupEvent),
) -> Result<(), SetupError> {
    let options = crate::ModelOptions {
        coreml_cache,
        ..crate::ModelOptions::default()
    };
    let started = std::time::Instant::now();
    std::thread::scope(|scope| {
        let opening = scope.spawn(|| crate::ModelSeparator::new(path, &options)?.warm_up());
        while !opening.is_finished() {
            progress(SetupEvent::Warming {
                seconds: started.elapsed().as_secs(),
            });
            std::thread::sleep(Duration::from_millis(500));
        }
        opening
            .join()
            .unwrap_or_else(|_| Err(crate::SeparateError::Model("the session panicked".into())))
            .map_err(|e| SetupError::Warm(e.to_string()))
    })
}

#[cfg(not(feature = "model"))]
fn warm(_: &Path, _: Option<PathBuf>, _: &dyn Fn(SetupEvent)) -> Result<(), SetupError> {
    Ok(())
}

