    /// The real setup, from a local copy of the author's weights served on localhost:
    ///
    /// ```text
    /// OPEN_JOCKEY_STEMS_WEIGHTS=<955717e8.safetensors> OPEN_JOCKEY_STEMS_MODEL=<out.onnx> \
    ///   cargo nextest run -p stems --run-ignored only real_setup
    /// ```
    ///
    /// On macOS it also warms CoreML, into `OPEN_JOCKEY_STEMS_COREML_CACHE` if set.
    #[test]
    #[ignore = "needs the author's weights (OPEN_JOCKEY_STEMS_WEIGHTS)"]
    fn real_setup_from_a_local_copy() {
        let weights =
            std::fs::read(std::env::var_os("OPEN_JOCKEY_STEMS_WEIGHTS").unwrap()).unwrap();
        let model = PathBuf::from(std::env::var_os("OPEN_JOCKEY_STEMS_MODEL").unwrap());
        let (url, server) = serve(vec![Answer::Body(weights)]);
        let mut plan = Plan::htdemucs(model.clone());
        plan.weights_url = url;
        plan.allow_http = true;
        plan.coreml_cache = std::env::var_os("OPEN_JOCKEY_STEMS_COREML_CACHE").map(PathBuf::from);
        let started = std::time::Instant::now();
        run(&plan, &|e| {
            if !matches!(e, SetupEvent::Downloading { .. }) {
                eprintln!("{:6.1} s {e:?}", started.elapsed().as_secs_f32());
            }
        })
        .unwrap();
        // With the model already installed nothing connects: the server is left waiting.
        drop(server);
        assert_eq!(sha256_hex(&std::fs::read(&model).unwrap()), FILLED_SHA256);
    }
