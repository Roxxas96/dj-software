    #[test]
    fn fill_checks_types_shapes_and_coverage() {
        let (graph, weights) = tiny();
        let filled = fill(&graph, &weights, &["x"]).unwrap();
        let model = onnx::ModelProto::decode(filled.as_slice()).unwrap();
        let body = model.graph.unwrap();
        assert_eq!(body.input.len(), 1);
        let w = body.initializer.iter().find(|i| i.name == "w").unwrap();
        assert_eq!(w.raw_data, [0x00, 0x3c, 0x00, 0xc0]);
        assert_eq!(w.dims, [2]);

        let tensor = |dtype, shape: Vec<usize>, bytes: &[u8]| {
            let view = safetensors::tensor::TensorView::new(dtype, shape, bytes).unwrap();
            safetensors::serialize([("w", view)], None).unwrap()
        };
        let wrong_shape = tensor(safetensors::Dtype::F16, vec![1, 2], &[0; 4]);
        let error = fill(&graph, &wrong_shape, &["x"]).unwrap_err().to_string();
        assert!(error.contains("shape"), "{error}");
        let wrong_type = tensor(safetensors::Dtype::BF16, vec![2], &[0; 4]);
        let error = fill(&graph, &wrong_type, &["x"]).unwrap_err().to_string();
        assert!(error.contains("F16"), "{error}");

        let extra = {
            let w = safetensors::tensor::TensorView::new(safetensors::Dtype::F16, vec![2], &[0; 4])
                .unwrap();
            let v = safetensors::tensor::TensorView::new(safetensors::Dtype::F16, vec![2], &[0; 4])
                .unwrap();
            safetensors::serialize([("v", v), ("w", w)], None).unwrap()
        };
        let error = fill(&graph, &extra, &["x"]).unwrap_err().to_string();
        assert!(error.contains("1 of the 2"), "{error}");
        let error = fill(&graph, &weights, &["x", "mag"])
            .unwrap_err()
            .to_string();
        assert!(error.contains("inputs left"), "{error}");
    }

