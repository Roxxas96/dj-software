//! `stems setup`: fetches the htdemucs weights from their author, fills the committed
//! weight-free graph with them and writes the model to the data folder (ruling R2; see
//! docs/stems-backend.md, "Model distribution" and "Weight-free graph and name map").
//!
//! Open Jockey never redistributes the weights. Their license is unclear: the author
//! trained them partly on data usable for research only.

